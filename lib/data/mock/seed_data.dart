  static PickupWindow _upcomingWindow({
    required DateTime now,
    required int startOffsetMinutes,
    int durationMinutes = 60,
  }) {
    final base = now.add(Duration(minutes: startOffsetMinutes));
    final roundedMinute = (base.minute ~/ 15) * 15;
    final start = DateTime(
      base.year,
      base.month,
      base.day,
      base.hour,
      roundedMinute,
    );
    return PickupWindow(
      start: start,
      end: start.add(Duration(minutes: durationMinutes)),
    );
  }

